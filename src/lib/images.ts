export const MAX_IMAGE_BYTES = 3 * 1024 * 1024; // 3 MB (o front já reduz a imagem antes de enviar)
export const MAX_WORK_PHOTOS = 12;

// Detecta o tipo real pelos primeiros bytes; nunca confiamos no tipo informado pelo navegador.
export function sniffImageType(buf: Uint8Array): 'image/jpeg' | 'image/png' | 'image/webp' | null {
  if (buf.length > 12 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'image/jpeg';
  if (buf.length > 12 && buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47) return 'image/png';
  if (buf.length > 12 && buf[0] === 0x52 && buf[1] === 0x49 && buf[2] === 0x46 && buf[3] === 0x46 && buf[8] === 0x57 && buf[9] === 0x45 && buf[10] === 0x42 && buf[11] === 0x50) return 'image/webp';
  return null;
}
